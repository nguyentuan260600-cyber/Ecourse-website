function buildSections(c: CourseSummary): CurriculumSection[] {
  if (c.slug === "fullstack-ai-engineering") {
    const mods = [
      "Tổng quan AI Engineering & thiết lập môi trường Next.js",
      "Tương tác LLM Streaming, AI SDK & Prompt Architecture",
      "Kiến trúc LangChain & chuỗi xử lý LCEL",
      "RAG toàn diện: Embeddings, Vector DB, Chunking & Hybrid Search",
      "Autonomous Agents & Tool Calling",
      "Đóng gói SaaS: quản lý người dùng & tích hợp thanh toán",
      "Tối ưu chi phí LLM: Caching, Guardrails & Evaluation",
      "Capstone: Triển khai hệ thống AI Customer Support",
    ];
    return mods.map((title, si) => ({
      id: `${c.id}-s${si + 1}`,
      title,
      lessons: Array.from({ length: si === 0 ? 3 : 8 }, (_, li) => ({
        id: `${c.id}-s${si + 1}-l${li + 1}`,
        title:
          si === 0
            ? ["Bức tranh toàn cảnh AI Engineer và stack công nghệ", "Khởi tạo dự án Next.js với Tailwind và shadcn/ui", "Cấu hình môi trường bảo mật API key"][li]
            : `Bài ${si + 1}.${li + 1}: ${title.split(":")[0]} — phần ${li + 1}`,
        type: li === 7 ? "quiz" : "video",
        durationSeconds: 900 + ((si * 7 + li * 13) % 20) * 60,
        isPreview: si === 0 && li < 2,
      })),
    }));
  }
  const sectionCount = Math.max(3, Math.min(8, Math.round(c.lessonCount / 8)));
  const per = Math.max(1, Math.floor(c.lessonCount / sectionCount));
  const avg = Math.floor(c.durationSeconds / Math.max(1, c.lessonCount));
  return Array.from({ length: sectionCount }, (_, si) => ({
    id: `${c.id}-s${si + 1}`,
    title: si === 0 ? "Giới thiệu & chuẩn bị" : si === sectionCount - 1 ? "Dự án tổng kết" : `Chương ${si + 1}: ${c.tags[(si - 1) % c.tags.length]} chuyên sâu`,
    lessons: Array.from({ length: per }, (_, li) => ({
      id: `${c.id}-s${si + 1}-l${li + 1}`,
      title: `Bài ${si + 1}.${li + 1}`,
      type: (li === per - 1 && si > 0 ? "quiz" : "video") as "quiz" | "video",
      durationSeconds: avg,
      isPreview: si === 0 && li === 0,
    })),
  }));
}

