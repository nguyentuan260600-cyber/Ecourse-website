/**
 * Generates supabase/seed.sql from the dev fixtures so the database and the
 * no-database demo mode show the same catalog.
 *
 *   node --conditions=react-server scripts/generate-seed.ts
 *
 * DEVELOPMENT ONLY. The generated seed refuses to run when app.environment = 'production'.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  buildFixtureDetail,
  fixtureCategories,
  fixtureCourses,
  fixtureInstructors,
} from "../src/features/courses/fixtures.ts";

const q = (s: string | null | undefined) => (s == null ? "null" : `'${s.replace(/'/g, "''")}'`);
const id = (key: string) => `md5('ks:${key}')::uuid`;
const arr = (xs: string[]) => `array[${xs.map(q).join(",")}]::text[]`;

const out: string[] = [];
out.push(`-- AUTO-GENERATED by scripts/generate-seed.ts — DEVELOPMENT DATA ONLY.
-- Do not run against production. Numbers here are fixtures, not real analytics.
do $$ begin
  if coalesce(current_setting('app.environment', true), '') = 'production' then
    raise exception 'Refusing to seed a production database';
  end if;
end $$;
`);

out.push("-- Instructors (auth users + profiles)");
for (const i of fixtureInstructors) {
  out.push(
    `insert into auth.users (id, email, raw_user_meta_data) values (${id(i.id)}, ${q(`${i.slug}@example.dev`)}, jsonb_build_object('display_name', ${q(i.name)})) on conflict (id) do nothing;`,
    `update public.profiles set display_name = ${q(i.name)}, avatar_url = ${q(i.avatarUrl)}, bio = ${q(i.biography)} where id = ${id(i.id)};`,
    `insert into public.instructor_profiles (user_id, slug, headline, biography, expertise, status) values (${id(i.id)}, ${q(i.slug)}, ${q(i.headline)}, ${q(i.biography)}, ${arr(i.expertise)}, 'active') on conflict (user_id) do nothing;`,
    `insert into public.user_roles (user_id, role_id) select ${id(i.id)}, id from public.roles where code = 'instructor' on conflict do nothing;`,
  );
}

out.push("\n-- Categories");
fixtureCategories.forEach((c, n) =>
  out.push(
    `insert into public.categories (id, name, slug, description, tags, sort_order) values (${id(c.id)}, ${q(c.name)}, ${q(c.slug)}, ${q(c.description)}, ${arr(c.tags)}, ${n}) on conflict (slug) do nothing;`,
  ),
);

out.push("\n-- Courses, curriculum, tags");
for (const c of fixtureCourses) {
  const d = buildFixtureDetail(c);
  const catId = fixtureCategories.find((x) => x.slug === c.category.slug)!.id;
  out.push(
    `insert into public.courses (id, category_id, title, slug, short_description, description, thumbnail_url, price_vnd, compare_at_price_vnd, level, status, badge, objectives, requirements, includes, published_at) values (${id(c.id)}, ${id(catId)}, ${q(c.title)}, ${q(c.slug)}, ${q(c.shortDescription)}, ${q(d.description)}, ${q(c.thumbnailUrl)}, ${c.priceVnd}, ${c.compareAtPriceVnd ?? "null"}, ${q(c.level)}, 'published', ${q(c.badge)}, ${q(JSON.stringify(d.objectives))}::jsonb, ${arr(d.requirements)}, ${arr(d.includes)}, ${q(c.publishedAt)}::timestamptz) on conflict (slug) do nothing;`,
    `insert into public.course_instructors (course_id, instructor_id, is_primary) values (${id(c.id)}, ${id(c.instructor.id)}, true) on conflict do nothing;`,
  );
  for (const t of c.tags) out.push(`insert into public.course_tags (course_id, tag) values (${id(c.id)}, ${q(t)}) on conflict do nothing;`);
  d.sections.forEach((s, si) => {
    out.push(
      `insert into public.course_sections (id, course_id, title, sort_order) values (${id(s.id)}, ${id(c.id)}, ${q(s.title)}, ${si}) on conflict (id) do nothing;`,
    );
    s.lessons.forEach((l, li) =>
      out.push(
        `insert into public.lessons (id, section_id, title, slug, lesson_type, duration_seconds, is_preview, sort_order) values (${id(l.id)}, ${id(s.id)}, ${q(l.title)}, ${q(`bai-${si + 1}-${li + 1}`)}, ${q(l.type)}, ${l.durationSeconds}, ${l.isPreview}, ${li}) on conflict (id) do nothing;`,
      ),
    );
  });
}

out.push(`
-- Sample coupon (dev)
insert into public.coupons (code, description, discount_type, discount_value, max_discount_vnd, expires_at, max_redemptions)
values ('CHAOMUNG10', 'Giảm 10% cho học viên mới (dữ liệu mẫu)', 'percent', 10, 300000, now() + interval '1 year', 1000)
on conflict (code) do nothing;
`);

writeFileSync(join(import.meta.dirname, "..", "supabase", "seed.sql"), out.join("\n") + "\n");
console.log(`seed.sql: ${fixtureInstructors.length} giảng viên, ${fixtureCategories.length} danh mục, ${fixtureCourses.length} khoá học`);
