// Concatenates all migrations (+ optional dev seed) into supabase/setup.sql,
// for a one-time paste into the Supabase SQL Editor on a NEW, EMPTY project.
//   node scripts/bundle-setup.mjs           -> migrations + dev seed
//   node scripts/bundle-setup.mjs --no-seed -> migrations only (production)
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..", "supabase");
const withSeed = !process.argv.includes("--no-seed");
const parts = [
  "-- Khai Sáng: full database setup. Run ONCE on a new, empty Supabase project.\n-- Generated by scripts/bundle-setup.mjs — do not edit by hand.\n",
];
for (const f of readdirSync(join(root, "migrations")).sort()) {
  parts.push(`\n-- ===== migrations/${f} =====\n`, readFileSync(join(root, "migrations", f), "utf8"));
}
if (withSeed) parts.push("\n-- ===== seed.sql (DEV SAMPLE DATA) =====\n", readFileSync(join(root, "seed.sql"), "utf8"));
const out = join(root, withSeed ? "setup.sql" : "setup.production.sql");
writeFileSync(out, parts.join("\n"));
console.log(`Đã tạo ${out}`);
